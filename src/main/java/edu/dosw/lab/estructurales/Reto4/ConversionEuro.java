package edu.dosw.lab.estructurales.Reto4;

public class ConversionEuro {
    public double euroToCop(double amount){
        return amount * 4687.80;
    }

    public double euroToYen(double amount){
        return amount * 171.87;
    }

    public double euroToDollar(double amount){
        return amount * 1.16;
    }
    
}
