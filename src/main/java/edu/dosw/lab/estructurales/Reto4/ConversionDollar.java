package edu.dosw.lab.estructurales;

public class ConversionDollar {
    public double dollarToCop(double amount){
        return amount * 4031.83;
    }

    public double dollarToYen(double amount){
        return amount * 147.82;
    }

    public double dollarToEuro(double amount){
        return amount * 0.86;
    }
    
}
