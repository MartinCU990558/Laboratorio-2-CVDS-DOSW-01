package edu.dosw.lab.estructurales.Reto4;

public class ConversionCop {
    public double copToDollar(double amount){
        return amount * 0.00025;
    }

    public double copToEuro(double amount){
        return amount * 0.00021;
    }

    public double copToYen(double amount){
        return amount * 0.037;
    }
    
}
