package edu.dosw.lab.estructurales.Reto4;

public class ConversionYen {
    public double yenToCop(double amount){
        return amount * 27.43;
    }

    public double yenToEuro(double amount){
        return amount * 0.0058;
    }

    public double yenToDollar(double amount){
        return amount * 0.0068;
    }
    
}
